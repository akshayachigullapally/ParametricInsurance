-- Roles are stored on users_credentials.role; the old lookup tables are no longer used.
DROP TABLE IF EXISTS user_roles;
DROP TABLE IF EXISTS roles;

CREATE TABLE IF NOT EXISTS users_credentials(
                                                id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                                email VARCHAR(255) NOT NULL UNIQUE,
    password VARCHAR(255) NOT NULL,
    full_name VARCHAR(150) NOT NULL,
    role VARCHAR(50) NOT NULL,
    enabled BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMP NOT NULL,
    updated_at TIMESTAMP NOT NULL
    );

CREATE TABLE IF NOT EXISTS user_profiles(
                                            id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                            auth_user_id BIGINT NOT NULL UNIQUE,
                                            phone_number VARCHAR(20),
    date_of_birth DATE,
    customer_segment VARCHAR(50) NOT NULL,
    status VARCHAR(50) NOT NULL,
    created_at TIMESTAMP NOT NULL,
    updated_at TIMESTAMP NOT NULL,
    CONSTRAINT fk_profile_auth_user
    FOREIGN KEY(auth_user_id) REFERENCES users_credentials(id)
    );

CREATE TABLE IF NOT EXISTS addresses(
                                        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                        user_profile_id BIGINT NOT NULL,
                                        address_line_one VARCHAR(255) NOT NULL,
    address_line_two VARCHAR(255),
    city VARCHAR(100) NOT NULL,
    state VARCHAR(100) NOT NULL,
    postal_code VARCHAR(20) NOT NULL,
    country VARCHAR(100) NOT NULL,
    primary_address BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMP NOT NULL,
    updated_at TIMESTAMP NOT NULL,
    CONSTRAINT fk_address_profile
    FOREIGN KEY(user_profile_id) REFERENCES user_profiles(id)
    );

CREATE TABLE IF NOT EXISTS refresh_tokens(
                                             id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                             user_id BIGINT NOT NULL,
                                             token VARCHAR(500) NOT NULL UNIQUE,
    expires_at TIMESTAMP NOT NULL,
    revoked BOOLEAN NOT NULL DEFAULT FALSE,
    created_at TIMESTAMP NOT NULL,
    CONSTRAINT fk_refresh_user
    FOREIGN KEY(user_id) REFERENCES users_credentials(id)
    );

CREATE TABLE IF NOT EXISTS sessions(
                                       id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                       user_id BIGINT NOT NULL,
                                       refresh_token_id BIGINT,
                                       device_name VARCHAR(150),
    ip_address VARCHAR(100),
    active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMP NOT NULL,
    last_accessed_at TIMESTAMP NOT NULL,
    CONSTRAINT fk_session_user
    FOREIGN KEY(user_id) REFERENCES users_credentials(id),
    CONSTRAINT fk_session_refresh
    FOREIGN KEY(refresh_token_id) REFERENCES refresh_tokens(id)
    );

CREATE INDEX IF NOT EXISTS idx_profile_auth_user
    ON user_profiles(auth_user_id);

CREATE INDEX IF NOT EXISTS idx_profile_status
    ON user_profiles(status);

CREATE INDEX IF NOT EXISTS idx_profile_segment
    ON user_profiles(customer_segment);

CREATE INDEX IF NOT EXISTS idx_address_profile
    ON addresses(user_profile_id);


-- Email verification and password reset were removed; clean up existing databases.
DROP TABLE IF EXISTS email_verification_tokens;
DROP TABLE IF EXISTS password_reset_tokens;
ALTER TABLE users_credentials DROP COLUMN IF EXISTS email_verified;
