CREATE TABLE IF NOT EXISTS notifications(
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    notification_reference VARCHAR(50) NOT NULL UNIQUE,
    recipient_user_id BIGINT,
    recipient_customer_id BIGINT,
    recipient_role VARCHAR(50),
    type VARCHAR(50) NOT NULL,
    title VARCHAR(150) NOT NULL,
    message VARCHAR(1000) NOT NULL,
    related_entity_type VARCHAR(50),
    related_entity_id BIGINT,
    is_read BOOLEAN NOT NULL DEFAULT FALSE,
    read_at TIMESTAMP,
    correlation_id VARCHAR(100),
    idempotency_key VARCHAR(255),
    created_at TIMESTAMP NOT NULL,
    updated_at TIMESTAMP
);
CREATE INDEX IF NOT EXISTS idx_notification_user ON notifications(recipient_user_id);
CREATE INDEX IF NOT EXISTS idx_notification_customer ON notifications(recipient_customer_id);
CREATE INDEX IF NOT EXISTS idx_notification_role ON notifications(recipient_role);
CREATE INDEX IF NOT EXISTS idx_notification_type ON notifications(type);
CREATE UNIQUE INDEX IF NOT EXISTS uq_notification_idempotency ON notifications(idempotency_key);
CREATE INDEX IF NOT EXISTS idx_notification_created ON notifications(created_at);

