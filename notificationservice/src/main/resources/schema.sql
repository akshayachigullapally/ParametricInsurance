CREATE TABLE IF NOT EXISTS notifications(
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    notification_reference VARCHAR(50) NOT NULL UNIQUE,
    recipient_user_id BIGINT,
    recipient_customer_id BIGINT,
    recipient_role VARCHAR(50),
    type VARCHAR(50) NOT NULL,
    title VARCHAR(150) NOT NULL,
    message VARCHAR(1000) NOT NULL,
    related_entity_type VARCHAR(50),
    related_entity_id BIGINT,
    is_read BOOLEAN NOT NULL DEFAULT FALSE,
    read_at TIMESTAMP,
    delivery_channel VARCHAR(30) NOT NULL,
    delivery_status VARCHAR(30) NOT NULL,
    retry_count INT NOT NULL DEFAULT 0,
    max_retries INT NOT NULL DEFAULT 3,
    correlation_id VARCHAR(100),
    idempotency_key VARCHAR(255),
    created_at TIMESTAMP NOT NULL,
    updated_at TIMESTAMP
);
CREATE INDEX IF NOT EXISTS idx_notification_user ON notifications(recipient_user_id);
CREATE INDEX IF NOT EXISTS idx_notification_customer ON notifications(recipient_customer_id);
CREATE INDEX IF NOT EXISTS idx_notification_role ON notifications(recipient_role);
CREATE INDEX IF NOT EXISTS idx_notification_status ON notifications(delivery_status);
CREATE INDEX IF NOT EXISTS idx_notification_type ON notifications(type);
CREATE UNIQUE INDEX IF NOT EXISTS uq_notification_idempotency ON notifications(idempotency_key);
CREATE INDEX IF NOT EXISTS idx_notification_created ON notifications(created_at);

CREATE TABLE IF NOT EXISTS notification_templates(
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    template_code VARCHAR(50) NOT NULL UNIQUE,
    notification_type VARCHAR(50) NOT NULL,
    title_template VARCHAR(150) NOT NULL,
    message_template VARCHAR(1000) NOT NULL,
    default_channel VARCHAR(30) NOT NULL DEFAULT 'IN_APP',
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMP NOT NULL,
    updated_at TIMESTAMP
);
CREATE INDEX IF NOT EXISTS idx_template_type ON notification_templates(notification_type);

CREATE TABLE IF NOT EXISTS notification_preferences(
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT,
    customer_id BIGINT,
    notification_type VARCHAR(50) NOT NULL,
    in_app_enabled BOOLEAN NOT NULL DEFAULT TRUE,
    email_enabled BOOLEAN NOT NULL DEFAULT FALSE,
    sms_enabled BOOLEAN NOT NULL DEFAULT FALSE,
    created_at TIMESTAMP NOT NULL,
    updated_at TIMESTAMP
);
CREATE INDEX IF NOT EXISTS idx_pref_user ON notification_preferences(user_id);
CREATE INDEX IF NOT EXISTS idx_pref_customer ON notification_preferences(customer_id);

CREATE TABLE IF NOT EXISTS delivery_attempts(
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    notification_id BIGINT NOT NULL,
    delivery_channel VARCHAR(30) NOT NULL,
    delivery_status VARCHAR(30) NOT NULL,
    attempt_number INT NOT NULL DEFAULT 1,
    error_message VARCHAR(500),
    attempted_at TIMESTAMP NOT NULL,
    completed_at TIMESTAMP
);
CREATE INDEX IF NOT EXISTS idx_delivery_notification ON delivery_attempts(notification_id);

CREATE TABLE IF NOT EXISTS audit_events(
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_reference VARCHAR(50) NOT NULL UNIQUE,
    event_type VARCHAR(100) NOT NULL,
    actor_user_id BIGINT,
    actor_role VARCHAR(50),
    entity_type VARCHAR(50) NOT NULL,
    entity_id BIGINT,
    description VARCHAR(1000) NOT NULL,
    correlation_id VARCHAR(100),
    created_at TIMESTAMP NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_audit_entity ON audit_events(entity_type,entity_id);
CREATE INDEX IF NOT EXISTS idx_audit_created ON audit_events(created_at);
CREATE INDEX IF NOT EXISTS idx_audit_actor ON audit_events(actor_user_id,created_at);

CREATE TABLE IF NOT EXISTS default_templates(
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    notification_type VARCHAR(50) NOT NULL UNIQUE,
    title_template VARCHAR(150) NOT NULL,
    message_template VARCHAR(1000) NOT NULL,
    default_channel VARCHAR(30) NOT NULL DEFAULT 'IN_APP',
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMP NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_default_template_type ON default_templates(notification_type);
