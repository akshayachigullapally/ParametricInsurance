CREATE TABLE IF NOT EXISTS pricing_rules(
                              id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                              product_id BIGINT NOT NULL,
                              base_annual_rate DECIMAL(10,6) NOT NULL,
                              minimum_premium DECIMAL(19,2) NOT NULL,
                              term_factor DECIMAL(10,4) NOT NULL,
                              location_zone_id BIGINT,
                              location_factor DECIMAL(10,4) NOT NULL,
                              status VARCHAR(30) NOT NULL,
                              effective_from DATE NOT NULL,
                              effective_to DATE,
                              created_by BIGINT NOT NULL,
                              created_at TIMESTAMP NOT NULL,
                              updated_by BIGINT,
                              updated_at TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_pricing_product
    ON pricing_rules(product_id);

CREATE INDEX IF NOT EXISTS idx_pricing_product_status
    ON pricing_rules(product_id,status);

CREATE INDEX IF NOT EXISTS idx_pricing_location
    ON pricing_rules(location_zone_id);

CREATE TABLE IF NOT EXISTS quotes(
                       id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                       quote_reference VARCHAR(50) NOT NULL UNIQUE,
                       customer_id BIGINT NOT NULL,
                       product_id BIGINT NOT NULL,
                       location_zone_id BIGINT NOT NULL,
                       sum_insured DECIMAL(19,2) NOT NULL,
                       term_months INTEGER NOT NULL,
                       annual_rate DECIMAL(10,6) NOT NULL,
                       term_factor DECIMAL(10,4) NOT NULL,
                       location_factor DECIMAL(10,4) NOT NULL,
                       premium_amount DECIMAL(19,2) NOT NULL,
                       status VARCHAR(30) NOT NULL,
                       expires_at TIMESTAMP NOT NULL,
                       created_at TIMESTAMP NOT NULL,
                       accepted_at TIMESTAMP,
                       policy_id BIGINT,
                       policy_number VARCHAR(50),
                       consumed_at TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_quote_customer
    ON quotes(customer_id);

CREATE INDEX IF NOT EXISTS idx_quote_product
    ON quotes(product_id);

CREATE INDEX IF NOT EXISTS idx_quote_status
    ON quotes(status);

CREATE INDEX IF NOT EXISTS idx_quote_policy
    ON quotes(policy_id);

CREATE TABLE IF NOT EXISTS payments(
                         id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                         payment_reference VARCHAR(50) NOT NULL UNIQUE,
                         customer_id BIGINT NOT NULL,
                         policy_id BIGINT NOT NULL,
                         policy_number VARCHAR(50) NOT NULL,
                         quote_id BIGINT,
                         amount DECIMAL(19,2) NOT NULL,
                         method VARCHAR(30) NOT NULL,
                         status VARCHAR(30) NOT NULL,
                         external_reference VARCHAR(100),
                         failure_reason VARCHAR(500),
                         attempt_number INTEGER NOT NULL,
                         created_at TIMESTAMP NOT NULL,
                         completed_at TIMESTAMP,
                         updated_at TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_payment_customer
    ON payments(customer_id);

CREATE INDEX IF NOT EXISTS idx_payment_policy
    ON payments(policy_id);

CREATE INDEX IF NOT EXISTS idx_payment_quote
    ON payments(quote_id);

CREATE INDEX IF NOT EXISTS idx_payment_status
    ON payments(status);

CREATE TABLE IF NOT EXISTS payouts(
                        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                        payout_reference VARCHAR(50) NOT NULL UNIQUE,
                        customer_id BIGINT NOT NULL,
                        claim_id BIGINT NOT NULL UNIQUE,
                        claim_number VARCHAR(50) NOT NULL,
                        policy_id BIGINT NOT NULL,
                        trigger_event_id BIGINT,
                        amount DECIMAL(19,2) NOT NULL,
                        status VARCHAR(30) NOT NULL,
                        external_reference VARCHAR(100),
                        failure_reason VARCHAR(500),
                        retry_count INTEGER NOT NULL,
                        created_at TIMESTAMP NOT NULL,
                        processed_at TIMESTAMP,
                        updated_at TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_payout_customer
    ON payouts(customer_id);

CREATE INDEX IF NOT EXISTS idx_payout_status
    ON payouts(status);

CREATE INDEX IF NOT EXISTS idx_payout_policy
    ON payouts(policy_id);

CREATE INDEX IF NOT EXISTS idx_payout_event
    ON payouts(trigger_event_id);

CREATE TABLE IF NOT EXISTS financial_transactions(
                                      id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                      transaction_reference VARCHAR(50) NOT NULL UNIQUE,
                                      customer_id BIGINT,
                                      policy_id BIGINT,
                                      quote_id BIGINT,
                                      payment_id BIGINT,
                                      payout_id BIGINT,
                                      transaction_type VARCHAR(30) NOT NULL,
                                      amount DECIMAL(19,2) NOT NULL,
                                      status VARCHAR(30) NOT NULL,
                                      description VARCHAR(500),
                                      created_at TIMESTAMP NOT NULL
);

CREATE INDEX IF NOT EXISTS idx_ft_customer
    ON financial_transactions(customer_id);

CREATE INDEX IF NOT EXISTS idx_ft_policy
    ON financial_transactions(policy_id);

CREATE INDEX IF NOT EXISTS idx_ft_type
    ON financial_transactions(transaction_type);

CREATE INDEX IF NOT EXISTS idx_ft_status
    ON financial_transactions(status);

CREATE TABLE IF NOT EXISTS reconciliation_records(
                                      id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                      reconciliation_reference VARCHAR(50) NOT NULL UNIQUE,
                                      transaction_type VARCHAR(30) NOT NULL,
                                      entity_id BIGINT NOT NULL,
                                      entity_reference VARCHAR(50) NOT NULL,
                                      amount DECIMAL(19,2) NOT NULL,
                                      status VARCHAR(30) NOT NULL,
                                      notes VARCHAR(500),
                                      reconciled_by BIGINT,
                                      created_at TIMESTAMP NOT NULL,
                                      reconciled_at TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_rr_type
    ON reconciliation_records(transaction_type);

CREATE INDEX IF NOT EXISTS idx_rr_status
    ON reconciliation_records(status);