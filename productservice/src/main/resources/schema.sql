CREATE TABLE IF NOT EXISTS products(
                                       id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                       product_code VARCHAR(50) NOT NULL UNIQUE,
    name VARCHAR(150) NOT NULL,
    description VARCHAR(1000),
    category VARCHAR(50) NOT NULL,
    status VARCHAR(50) NOT NULL,
    minimum_sum_insured DECIMAL(15,2) NOT NULL,
    maximum_sum_insured DECIMAL(15,2) NOT NULL,
    minimum_term_months INT NOT NULL,
    maximum_term_months INT NOT NULL,
    eligibility_description VARCHAR(1000),
    peril_code VARCHAR(50),
    measurement_type VARCHAR(50),
    measurement_unit VARCHAR(40),
    threshold_value DECIMAL(19,4),
    comparison_operator VARCHAR(40),
    aggregation_type VARCHAR(40),
    observation_window_hours INT,
    minimum_observation_count INT,
    trigger_description VARCHAR(1000),
    trigger_sync_status VARCHAR(20),
    trigger_synced_at TIMESTAMP,
    trigger_sync_error VARCHAR(1000),
    created_by BIGINT NOT NULL,
    created_at TIMESTAMP NOT NULL,
    updated_at TIMESTAMP NOT NULL
    );

CREATE TABLE IF NOT EXISTS coverages(
                                        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                        product_id BIGINT NOT NULL,
                                        coverage_code VARCHAR(50) NOT NULL,
    name VARCHAR(150) NOT NULL,
    description VARCHAR(1000),
    coverage_limit DECIMAL(15,2),
    mandatory BOOLEAN NOT NULL DEFAULT FALSE,
    active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMP NOT NULL,
    updated_at TIMESTAMP NOT NULL,
    CONSTRAINT fk_coverage_product
    FOREIGN KEY(product_id) REFERENCES products(id),
    CONSTRAINT uk_product_coverage
    UNIQUE(product_id,coverage_code)
    );

CREATE INDEX IF NOT EXISTS idx_product_code
    ON products(product_code);

CREATE INDEX IF NOT EXISTS idx_product_category
    ON products(category);

CREATE INDEX IF NOT EXISTS idx_product_status
    ON products(status);

CREATE INDEX IF NOT EXISTS idx_coverage_product
    ON coverages(product_id);

CREATE TABLE IF NOT EXISTS policies(
                                       id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                       policy_number VARCHAR(50) NOT NULL UNIQUE,
    customer_id BIGINT NOT NULL,
    product_id BIGINT NOT NULL,
    product_code VARCHAR(50) NOT NULL,
    product_name VARCHAR(150) NOT NULL,
    sum_insured DECIMAL(15,2) NOT NULL,
    premium_amount DECIMAL(15,2),
    term_months INT NOT NULL,
    start_date DATE,
    end_date DATE,
    status VARCHAR(50) NOT NULL,
    rejection_reason VARCHAR(500),
    reviewed_by BIGINT,
    reviewed_at TIMESTAMP,
    created_at TIMESTAMP NOT NULL,
    updated_at TIMESTAMP NOT NULL,
    location_zone_id BIGINT NOT NULL,
    trigger_snapshot_id BIGINT,
    CONSTRAINT fk_policy_product
    FOREIGN KEY(product_id) REFERENCES products(id)
    );

CREATE INDEX IF NOT EXISTS idx_policy_number
    ON policies(policy_number);

CREATE INDEX IF NOT EXISTS idx_policy_customer
    ON policies(customer_id);

CREATE INDEX IF NOT EXISTS idx_policy_product
    ON policies(product_id);

CREATE INDEX IF NOT EXISTS idx_policy_status
    ON policies(status);

CREATE INDEX IF NOT EXISTS idx_policy_customer_status
    ON policies(customer_id,status);

CREATE INDEX IF NOT EXISTS idx_policies_location_zone
    ON policies(location_zone_id);

CREATE TABLE IF NOT EXISTS policy_trigger_snapshots(
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    policy_id BIGINT NOT NULL UNIQUE,
    peril_code VARCHAR(50),
    trigger_metric VARCHAR(40),
    trigger_operator VARCHAR(40),
    trigger_threshold DECIMAL(19,4),
    trigger_duration_hours INT,
    trigger_aggregation_type VARCHAR(40),
    trigger_min_observation_count INT,
    product_id BIGINT,
    product_code VARCHAR(50),
    measurement_type VARCHAR(50),
    measurement_unit VARCHAR(40),
    threshold_value DECIMAL(19,4),
    comparison_operator VARCHAR(40),
    aggregation_type VARCHAR(40),
    observation_window_hours INT,
    minimum_observation_count INT,
    trigger_description VARCHAR(1000),
    captured_at TIMESTAMP,
    created_at TIMESTAMP NOT NULL,
    CONSTRAINT fk_snapshot_policy
    FOREIGN KEY(policy_id) REFERENCES policies(id)
    );

CREATE INDEX IF NOT EXISTS idx_snapshot_policy
    ON policy_trigger_snapshots(policy_id);

CREATE TABLE IF NOT EXISTS policy_status_history(
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    policy_id BIGINT NOT NULL,
    old_status VARCHAR(50),
    new_status VARCHAR(50) NOT NULL,
    changed_by BIGINT,
    change_reason VARCHAR(500),
    changed_at TIMESTAMP NOT NULL,
    CONSTRAINT fk_history_policy
    FOREIGN KEY(policy_id) REFERENCES policies(id)
    );

CREATE INDEX IF NOT EXISTS idx_history_policy
    ON policy_status_history(policy_id);

CREATE INDEX IF NOT EXISTS idx_history_policy_changed
    ON policy_status_history(policy_id,changed_at);

CREATE TABLE IF NOT EXISTS product_threshold_history(
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id BIGINT NOT NULL,
    product_code VARCHAR(50) NOT NULL,
    previous_peril_code VARCHAR(50),
    new_peril_code VARCHAR(50),
    previous_measurement_type VARCHAR(50),
    new_measurement_type VARCHAR(50),
    previous_measurement_unit VARCHAR(40),
    new_measurement_unit VARCHAR(40),
    previous_threshold_value DECIMAL(19,4),
    new_threshold_value DECIMAL(19,4),
    previous_comparison_operator VARCHAR(40),
    new_comparison_operator VARCHAR(40),
    previous_aggregation_type VARCHAR(40),
    new_aggregation_type VARCHAR(40),
    previous_observation_window_hours INT,
    new_observation_window_hours INT,
    previous_minimum_observation_count INT,
    new_minimum_observation_count INT,
    changed_by BIGINT,
    change_reason VARCHAR(500),
    changed_at TIMESTAMP NOT NULL,
    trigger_sync_status VARCHAR(20),
    CONSTRAINT fk_product_threshold_history
    FOREIGN KEY(product_id) REFERENCES products(id)
    );

CREATE INDEX IF NOT EXISTS idx_product_threshold_history_product
    ON product_threshold_history(product_id,changed_at);

