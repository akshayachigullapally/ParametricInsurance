CREATE TABLE IF NOT EXISTS claims(
                       id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                       claim_number VARCHAR(50) NOT NULL UNIQUE,
                       customer_id BIGINT NOT NULL,
                       policy_id BIGINT NOT NULL,
                       policy_number VARCHAR(50),
                       product_id BIGINT,

                       incident_type VARCHAR(100) NOT NULL,
                       incident_date DATE NOT NULL,
                       incident_location VARCHAR(255) NOT NULL,
                       description VARCHAR(1000) NOT NULL,

                       claimed_amount DECIMAL(15,2) NOT NULL,
                       approved_amount DECIMAL(15,2),

                       status VARCHAR(50) NOT NULL,
                       rejection_reason VARCHAR(500),

                       reviewed_by BIGINT,
                       reviewed_at TIMESTAMP,
                       submitted_at TIMESTAMP NOT NULL,
                       updated_at TIMESTAMP NOT NULL,

                       trigger_event_id BIGINT,
                       trigger_event_reference VARCHAR(50),
                       trigger_definition_id BIGINT,
                       peril_id BIGINT,
                       location_zone_id BIGINT,

                       claim_source VARCHAR(20) DEFAULT 'AUTO_TRIGGERED',
                       manual_review_required BOOLEAN DEFAULT FALSE,
                       trigger_detection_status VARCHAR(50),
                       manual_review_reason VARCHAR(500),
                       evidence_description VARCHAR(2000),
                       customer_confirmed_loss BOOLEAN DEFAULT FALSE,
                       created_from_trigger_event BOOLEAN DEFAULT FALSE,
                       investigation_result VARCHAR(2000),
                       investigated_by BIGINT,
                       investigated_at TIMESTAMP,
                       payout_requested BOOLEAN DEFAULT FALSE
);

CREATE INDEX IF NOT EXISTS idx_claims_customer
    ON claims(customer_id);

CREATE INDEX IF NOT EXISTS idx_claims_policy
    ON claims(policy_id);

CREATE INDEX IF NOT EXISTS idx_claims_status
    ON claims(status);

CREATE INDEX IF NOT EXISTS idx_claims_submitted_at
    ON claims(submitted_at);

CREATE INDEX IF NOT EXISTS idx_claims_trigger_event
    ON claims(trigger_event_id);

CREATE UNIQUE INDEX IF NOT EXISTS uq_claims_policy_trigger_event
    ON claims(policy_id,trigger_event_id);

CREATE INDEX IF NOT EXISTS idx_claims_trigger_definition
    ON claims(trigger_definition_id);

CREATE INDEX IF NOT EXISTS idx_claims_peril
    ON claims(peril_id);

CREATE INDEX IF NOT EXISTS idx_claims_location_zone
    ON claims(location_zone_id);

CREATE INDEX IF NOT EXISTS idx_claims_manual_review
    ON claims(manual_review_required);

CREATE INDEX IF NOT EXISTS idx_claims_claim_source
    ON claims(claim_source);

CREATE TABLE IF NOT EXISTS claim_timeline(
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    claim_id BIGINT NOT NULL,
    claim_number VARCHAR(50) NOT NULL,
    customer_id BIGINT NOT NULL,
    old_status VARCHAR(50),
    new_status VARCHAR(50) NOT NULL,
    action VARCHAR(100) NOT NULL,
    action_by BIGINT,
    action_by_role VARCHAR(50),
    notes VARCHAR(1000),
    created_at TIMESTAMP NOT NULL
);

CREATE INDEX IF NOT EXISTS idx_claim_timeline_claim
    ON claim_timeline(claim_id);

CREATE INDEX IF NOT EXISTS idx_claim_timeline_customer
    ON claim_timeline(customer_id);

CREATE INDEX IF NOT EXISTS idx_claim_timeline_created_at
    ON claim_timeline(created_at);

-- Trigger measurement captured on automatic claims (explains the payout to the customer)
ALTER TABLE claims ADD COLUMN IF NOT EXISTS trigger_measurement_type VARCHAR(50);
ALTER TABLE claims ADD COLUMN IF NOT EXISTS trigger_measurement_unit VARCHAR(30);
ALTER TABLE claims ADD COLUMN IF NOT EXISTS trigger_observed_value DECIMAL(15,4);
ALTER TABLE claims ADD COLUMN IF NOT EXISTS trigger_threshold_value DECIMAL(15,4);
ALTER TABLE claims ADD COLUMN IF NOT EXISTS trigger_comparison_operator VARCHAR(40);
ALTER TABLE claims ADD COLUMN IF NOT EXISTS trigger_window_start TIMESTAMP;
ALTER TABLE claims ADD COLUMN IF NOT EXISTS trigger_window_end TIMESTAMP;

-- Evidence uploaded by the customer (photos / documents). Files live on disk.
CREATE TABLE IF NOT EXISTS claim_documents(
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    claim_id BIGINT NOT NULL,
    original_file_name VARCHAR(255) NOT NULL,
    stored_file_name VARCHAR(100) NOT NULL UNIQUE,
    content_type VARCHAR(100) NOT NULL,
    size_bytes BIGINT NOT NULL,
    uploaded_by BIGINT NOT NULL,
    uploaded_at TIMESTAMP NOT NULL
);

CREATE INDEX IF NOT EXISTS idx_claim_documents_claim
    ON claim_documents(claim_id);

