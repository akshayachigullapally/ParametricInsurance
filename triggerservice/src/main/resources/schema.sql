CREATE TABLE IF NOT EXISTS current_measurements(
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id BIGINT NOT NULL,
    location_zone_id BIGINT NOT NULL,
    measurement_type VARCHAR(40) NOT NULL,
    measurement_unit VARCHAR(40) NOT NULL,
    current_value DECIMAL(19,4) NOT NULL,
    recorded_by BIGINT NOT NULL,
    recorded_at TIMESTAMP NOT NULL,
    updated_at TIMESTAMP NOT NULL,
    CONSTRAINT uq_current_measurement_product_zone UNIQUE(product_id,location_zone_id),
    CONSTRAINT chk_current_measurement_value CHECK(current_value>=0)
);


CREATE TABLE IF NOT EXISTS perils(
                       id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                       peril_code VARCHAR(50) NOT NULL UNIQUE,
                       peril_name VARCHAR(100) NOT NULL,
                       description VARCHAR(500) NOT NULL,
                       status VARCHAR(20) NOT NULL,
                       created_by BIGINT NOT NULL,
                       created_at TIMESTAMP NOT NULL,
                       updated_by BIGINT,
                       updated_at TIMESTAMP,
                       CONSTRAINT chk_peril_status CHECK(status IN ('ACTIVE','INACTIVE','ARCHIVED'))
);

CREATE TABLE IF NOT EXISTS location_zones(
                               id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                               zone_code VARCHAR(50) NOT NULL UNIQUE,
                               zone_name VARCHAR(100) NOT NULL,
                               country VARCHAR(100) NOT NULL,
                               state VARCHAR(100) NOT NULL,
                               district VARCHAR(100) NOT NULL,
                               postal_code VARCHAR(20),
                               latitude DECIMAL(10,7) NOT NULL,
                               longitude DECIMAL(10,7) NOT NULL,
                               radius_km DECIMAL(10,2) NOT NULL,
                               status VARCHAR(20) NOT NULL,
                               created_by BIGINT NOT NULL,
                               created_at TIMESTAMP NOT NULL,
                               updated_by BIGINT,
                               updated_at TIMESTAMP,
                               CONSTRAINT chk_location_zone_latitude CHECK(latitude>=-90 AND latitude<=90),
                               CONSTRAINT chk_location_zone_longitude CHECK(longitude>=-180 AND longitude<=180),
                               CONSTRAINT chk_location_zone_radius CHECK(radius_km>0),
                               CONSTRAINT chk_location_zone_status CHECK(status IN ('ACTIVE','INACTIVE','ARCHIVED'))
);

-- Underwriting controls: a raised weather alert pauses new sales in the zone, and
-- max_exposure caps the total sum insured of open policies there (NULL = no cap).
ALTER TABLE location_zones ADD COLUMN IF NOT EXISTS weather_alert BOOLEAN DEFAULT FALSE NOT NULL;
ALTER TABLE location_zones ADD COLUMN IF NOT EXISTS alert_message VARCHAR(500);
ALTER TABLE location_zones ADD COLUMN IF NOT EXISTS alert_raised_at TIMESTAMP;
ALTER TABLE location_zones ADD COLUMN IF NOT EXISTS max_exposure DECIMAL(18,2);

CREATE TABLE IF NOT EXISTS trigger_definitions(
                                    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                    definition_code VARCHAR(75) NOT NULL UNIQUE,
                                    definition_name VARCHAR(150) NOT NULL,
                                    description VARCHAR(500) NOT NULL,
                                    peril_id BIGINT NOT NULL,
                                    location_zone_id BIGINT NOT NULL,
                                    product_id BIGINT NOT NULL,
                                    measurement_type VARCHAR(40) NOT NULL,
                                    measurement_unit VARCHAR(40) NOT NULL,
                                    aggregation_type VARCHAR(40) NOT NULL,
                                    comparison_operator VARCHAR(40) NOT NULL,
                                    threshold_value DECIMAL(19,4) NOT NULL,
                                    observation_window_hours INT NOT NULL,
                                    minimum_observation_count INT NOT NULL,
                                    status VARCHAR(20) NOT NULL,
                                    effective_from DATE NOT NULL,
                                    effective_to DATE,
                                    created_by BIGINT NOT NULL,
                                    created_at TIMESTAMP NOT NULL,
                                    updated_by BIGINT,
                                    updated_at TIMESTAMP,
                                    CONSTRAINT fk_trigger_definition_peril
                                        FOREIGN KEY(peril_id) REFERENCES perils(id),
                                    CONSTRAINT fk_trigger_definition_zone
                                        FOREIGN KEY(location_zone_id) REFERENCES location_zones(id),
                                    CONSTRAINT chk_trigger_threshold CHECK(threshold_value>=0),
                                    CONSTRAINT chk_observation_window CHECK(observation_window_hours>0),
                                    CONSTRAINT chk_minimum_observations CHECK(minimum_observation_count>0),
                                    CONSTRAINT chk_effective_dates CHECK(effective_to IS NULL OR effective_to>=effective_from),
                                    CONSTRAINT chk_trigger_definition_status CHECK(status IN ('ACTIVE','INACTIVE','ARCHIVED'))
);

CREATE TABLE IF NOT EXISTS observations(
                             id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                             observation_reference VARCHAR(50) NOT NULL UNIQUE,
                             location_zone_id BIGINT NOT NULL,
                             measurement_type VARCHAR(40) NOT NULL,
                             measurement_unit VARCHAR(40) NOT NULL,
                             observed_value DECIMAL(19,4) NOT NULL,
                             observed_at TIMESTAMP NOT NULL,
                             source VARCHAR(30) NOT NULL,
                             source_reference VARCHAR(150),
                             status VARCHAR(20) NOT NULL,
                             received_by BIGINT NOT NULL,
                             received_at TIMESTAMP NOT NULL,
                             CONSTRAINT fk_observation_zone
                                 FOREIGN KEY(location_zone_id) REFERENCES location_zones(id)
);

CREATE TABLE IF NOT EXISTS trigger_evaluations(
                                    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                    evaluation_reference VARCHAR(50) NOT NULL UNIQUE,
                                    trigger_definition_id BIGINT NOT NULL,
                                    location_zone_id BIGINT NOT NULL,
                                    measurement_type VARCHAR(40) NOT NULL,
                                    window_start TIMESTAMP NOT NULL,
                                    window_end TIMESTAMP NOT NULL,
                                    observation_count INT NOT NULL,
                                    aggregated_value DECIMAL(19,4),
                                    threshold_value DECIMAL(19,4) NOT NULL,
                                    comparison_operator VARCHAR(40) NOT NULL,
                                    result VARCHAR(40) NOT NULL,
                                    evaluated_by BIGINT NOT NULL,
                                    evaluated_at TIMESTAMP NOT NULL,
                                    CONSTRAINT fk_evaluation_definition
                                        FOREIGN KEY(trigger_definition_id) REFERENCES trigger_definitions(id),
                                    CONSTRAINT fk_evaluation_zone
                                        FOREIGN KEY(location_zone_id) REFERENCES location_zones(id),
                                    CONSTRAINT chk_evaluation_window CHECK(window_end>=window_start),
                                    CONSTRAINT chk_evaluation_count CHECK(observation_count>=0)
);

CREATE TABLE IF NOT EXISTS trigger_events(
                               id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                               event_reference VARCHAR(50) NOT NULL UNIQUE,
                               trigger_definition_id BIGINT,
                               trigger_evaluation_id BIGINT UNIQUE,
                               peril_id BIGINT,
                               location_zone_id BIGINT NOT NULL,
                               product_id BIGINT NOT NULL,
                               measurement_type VARCHAR(40) NOT NULL,
                               measurement_unit VARCHAR(40) NOT NULL,
                               aggregated_value DECIMAL(19,4) NOT NULL,
                               threshold_value DECIMAL(19,4) NOT NULL,
                               window_start TIMESTAMP,
                               window_end TIMESTAMP,
                               status VARCHAR(30) NOT NULL,
                               detected_at TIMESTAMP NOT NULL,
                               reviewed_by BIGINT,
                               reviewed_at TIMESTAMP,
                               review_notes VARCHAR(500),
                               matched_policy_count INT DEFAULT 0,
                               claims_created_count INT DEFAULT 0,
                               notifications_created_count INT DEFAULT 0,
                               recorded_by BIGINT,
                               processed_at TIMESTAMP,
                               idempotency_key VARCHAR(200),
                               CONSTRAINT fk_event_definition
                                   FOREIGN KEY(trigger_definition_id) REFERENCES trigger_definitions(id),
                               CONSTRAINT fk_event_evaluation
                                   FOREIGN KEY(trigger_evaluation_id) REFERENCES trigger_evaluations(id),
                               CONSTRAINT fk_event_peril
                                   FOREIGN KEY(peril_id) REFERENCES perils(id),
                               CONSTRAINT fk_event_zone
                                   FOREIGN KEY(location_zone_id) REFERENCES location_zones(id),
                               CONSTRAINT chk_event_window CHECK(window_end>=window_start)
);

CREATE UNIQUE INDEX IF NOT EXISTS uq_trigger_events_idempotency_key ON trigger_events(idempotency_key);

CREATE TABLE IF NOT EXISTS monitor_runs(
                             id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                             started_at TIMESTAMP NOT NULL,
                             completed_at TIMESTAMP,
                             status VARCHAR(20) NOT NULL,
                             observations_processed INT NOT NULL DEFAULT 0,
                             events_created INT NOT NULL DEFAULT 0,
                             failure_message VARCHAR(500),
                             CONSTRAINT chk_monitor_observations CHECK(observations_processed>=0),
                             CONSTRAINT chk_monitor_events CHECK(events_created>=0),
                             CONSTRAINT chk_monitor_completion CHECK(completed_at IS NULL OR completed_at>=started_at)
);

CREATE TABLE IF NOT EXISTS monitor_checkpoints(
                                    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                    source_code VARCHAR(50) NOT NULL,
                                    location_zone_id BIGINT NOT NULL,
                                    last_processed_timestamp TIMESTAMP NOT NULL,
                                    last_observation_id BIGINT,
                                    CONSTRAINT fk_checkpoint_zone
                                        FOREIGN KEY(location_zone_id) REFERENCES location_zones(id),
                                    CONSTRAINT uq_checkpoint_source_zone
                                        UNIQUE(source_code,location_zone_id)
);

CREATE TABLE IF NOT EXISTS idempotency_records(
                                    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                    idempotency_key VARCHAR(200) NOT NULL UNIQUE,
                                    operation_type VARCHAR(50) NOT NULL,
                                    resource_id BIGINT,
                                    created_at TIMESTAMP NOT NULL
);

